export function getSekkiColor(date: Date): SekkiColor {
  const today = (date.getMonth() + 1) * 100 + date.getDate();
  return SEKKI_COLORS.reduce(
    (current, color) =>
      color.startMonth * 100 + color.startDay <= today ? color : current,
    SEKKI_COLORS[SEKKI_COLORS.length - 1]
  );
}

export function formatFluxTime(date: Date): string {
  return `${String(date.getHours()).padStart(2, "0")}:${String(date.getMinutes()).padStart(2, "0")}`;
}

export function millisecondsUntilNextMinute(date: Date): number {
  return 60000 - (date.getSeconds() * 1000 + date.getMilliseconds());
}
